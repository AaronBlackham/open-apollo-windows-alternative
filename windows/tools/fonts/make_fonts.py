def parse_sheet(text):
    """Return {glyph name: [row strings]} from a bitmap sheet."""
    glyphs = {}
    blocks = [b for b in text.strip("\n").split("\n\n") if b.strip()]
    for block in blocks:
        lines = [ln.split() for ln in block.strip("\n").split("\n")]
        names, rows = lines[0], lines[1:]
        if len(rows) < BASELINE_ROW + 1:
            raise ValueError(f"block {names} has only {len(rows)} rows")
        for row in rows:
            if len(row) != len(names):
                raise ValueError(f"block {names}: row {row} has wrong cell count")
        for i, name in enumerate(names):
            cells = [row[i] for row in rows]
            for cell in cells:
                if len(cell) != 5 or set(cell) - {"#", "."}:
                    raise ValueError(f"glyph {name}: bad row {cell!r}")
            if name in glyphs:
                raise ValueError(f"glyph {name} defined twice")
            glyphs[name] = cells
    return glyphs


def _simplify(points):
    """Drop collinear points from a closed polygon."""
    out = []
    n = len(points)
    for i in range(n):
        (x0, y0), (x1, y1), (x2, y2) = points[i - 1], points[i], points[(i + 1) % n]
        if (x1 - x0) * (y2 - y1) - (y1 - y0) * (x2 - x1) != 0:
            out.append(points[i])
    return out


def bitmap_contours(rows):
    """Trace the outline of the union of the 'on' pixels.

    Edges are oriented with the ink on the right, which makes outer contours
    clockwise and holes counter-clockwise (TrueType convention, y up). Where
    two pixels touch only at a corner the tracer turns right, so diagonal
    neighbours become separate contours that share a vertex instead of one
    self-touching figure-eight.
    """
    on = set()
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == "#":
                on.add((c, BASELINE_ROW - r))
    edges = []
    for x, y in on:
        if (x - 1, y) not in on:
            edges.append(((x, y), (x, y + 1)))  # left side, going up
        if (x, y + 1) not in on:
            edges.append(((x, y + 1), (x + 1, y + 1)))  # top, going right
        if (x + 1, y) not in on:
            edges.append(((x + 1, y + 1), (x + 1, y)))  # right side, going down
        if (x, y - 1) not in on:
            edges.append(((x + 1, y), (x, y)))  # bottom, going left
    outgoing = defaultdict(list)
    for start, end in edges:
        outgoing[start].append(end)

    used = set()
    contours = []
    for first in sorted(edges):
        if first in used:
            continue
        points = []
        edge = first
        while True:
            used.add(edge)
            points.append(edge[0])
            (sx, sy), (ex, ey) = edge
            choices = outgoing[(ex, ey)]
            if len(choices) == 1:
                nxt = choices[0]
            else:
                right = (ey - sy, -(ex - sx))
                nxt = next(p for p in choices if (p[0] - ex, p[1] - ey) == right)
            edge = ((ex, ey), nxt)
            if edge == first:
                break
            if edge in used:
                raise RuntimeError("pixel outline tracer looped")
        contours.append(_simplify(points))
    return [[(x * PX, y * PX) for x, y in c] for c in contours]


