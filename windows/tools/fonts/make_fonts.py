DIAG_GAP = round(SEG_GAP * math.sqrt(2))  # same visible gap as between segments


def segment_k():
    """Left verticals plus two diagonals that meet near the middle."""
    x_start = SEG_X0 + SEG_T + DIAG_GAP
    return [
        SEGMENT_SHAPES["f"],
        SEGMENT_SHAPES["e"],
        rising_bar(x_start, SEG_M + DIAG_GAP // 2, SEG_X1, CAP_HEIGHT),
        falling_bar(x_start, SEG_M - DIAG_GAP // 2, SEG_X1, 0),
    ]


def segment_z():
    """Top and bottom bars joined by one diagonal."""
    inset = 30
    return [
        SEGMENT_SHAPES["a"],
        SEGMENT_SHAPES["d"],
        rising_bar(SEG_X0 + inset, SEG_B + SEG_H + DIAG_GAP,
                   SEG_X1 - inset, SEG_TOP - SEG_H - DIAG_GAP),
    ]


def segment_plus():
    """Solid plus with pointed arm tips. The arms reach a little past the
    minus bar; at the minus bar's length the pointed tips make it a star."""
    cx, cy, h = CELL // 2, SEG_M, SEG_H
    r = 190  # tip distance from the centre
    return [[
        (cx - r, cy), (cx - r + h, cy + h), (cx - h, cy + h), (cx - h, cy + r - h),
        (cx, cy + r), (cx + h, cy + r - h), (cx + h, cy + h), (cx + r - h, cy + h),
        (cx + r, cy), (cx + r - h, cy - h), (cx + h, cy - h), (cx + h, cy - r + h),
        (cx, cy - r), (cx - h, cy - r + h), (cx - h, cy - h), (cx - r + h, cy - h),
    ]]


def segment_extras():
    """Glyphs that are not plain segment combinations: (contours, advance)."""
    dot_x = (NARROW - DOT) // 2
    lower_dot_y = SEG_M - 150 - DOT // 2
    upper_dot_y = SEG_M + 150 - DOT // 2
    comma = [
        (dot_x, DOT), (dot_x + DOT, DOT), (dot_x + DOT, 0),
        (dot_x + DOT // 2, -DOT), (dot_x - 5, -DOT),
        (dot_x + 30, 0), (dot_x, 0),
    ]
    inner = 50
    notdef = [
        [(SEG_X0, 0), (SEG_X0, CAP_HEIGHT), (SEG_X1, CAP_HEIGHT), (SEG_X1, 0)],
        [(SEG_X0 + inner, inner), (SEG_X1 - inner, inner),
         (SEG_X1 - inner, CAP_HEIGHT - inner), (SEG_X0 + inner, CAP_HEIGHT - inner)],
    ]
    return {
        ".notdef": (notdef, CELL),
        "space": ([], CELL),  # digit-width, so it pads readouts like a figure space
        "plus": (segment_plus(), CELL),
        "K": (segment_k(), CELL),
        "Z": (segment_z(), CELL),
        "period": ([square(dot_x, 0, DOT)], NARROW),
        "comma": ([comma], NARROW),
        "colon": ([square(dot_x, lower_dot_y, DOT), square(dot_x, upper_dot_y, DOT)], NARROW),
    }


