def signed_area(points):
    area = 0
    n = len(points)
    for i in range(n):
        x0, y0 = points[i]
        x1, y1 = points[(i + 1) % n]
        area += x0 * y1 - x1 * y0
    return area / 2


def make_glyph(contours):
    pen = TTGlyphPen(None)
    for contour in contours:
        pen.moveTo(contour[0])
        for pt in contour[1:]:
            pen.lineTo(pt)
        pen.closePath()
    return pen.glyph()


def build_font(path, family, ps_name, glyph_contours, advances, cmap,
               x_height, fixed_pitch):
    order = [".notdef", "space"] + [n for n in glyph_contours
                                    if n not in (".notdef", "space")]
    glyphs = {name: make_glyph(glyph_contours[name]) for name in order}

    fb = FontBuilder(UPM, isTTF=True)
    fb.updateHead(created=BUILD_TIME, modified=BUILD_TIME,
                  fontRevision=float(VERSION), lowestRecPPEM=8)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    glyf = fb.font["glyf"]
    fb.setupHorizontalMetrics(
        {name: (advances[name], getattr(glyf[name], "xMin", 0)) for name in order})
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT, lineGap=0)
    fb.setupNameTable({
        "copyright": NOTICE,
        "familyName": family,
        "styleName": "Regular",
        "uniqueFontIdentifier": f"{VERSION};AVIUM;{ps_name}",
        "fullName": f"{family} Regular",
        "version": f"Version {VERSION}",
        "psName": ps_name,
        "manufacturer": "Avium",
        "description": NOTICE,
    })
    panose = Panose(bFamilyType=2, bWeight=5, bProportion=9 if fixed_pitch else 0)
    fb.setupOS2(
        version=4,
        usWeightClass=400,
        usWidthClass=5,
        fsType=0,  # installable embedding
        ySubscriptXSize=650, ySubscriptYSize=600, ySubscriptYOffset=75,
        ySuperscriptXSize=650, ySuperscriptYSize=600, ySuperscriptYOffset=350,
        yStrikeoutSize=PX, yStrikeoutPosition=300,
        panose=panose,
        achVendID="NONE",
        fsSelection=0x40 | 0x80,  # REGULAR | USE_TYPO_METRICS
        sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
        usWinAscent=ASCENT, usWinDescent=DESCENT,
        ulCodePageRange1=1,  # Latin 1
        sxHeight=x_height,
        sCapHeight=CAP_HEIGHT,
    )
    fb.setupPost(isFixedPitch=1 if fixed_pitch else 0,
                 underlinePosition=-150, underlineThickness=PX)
    fb.save(path)


def build_pixel(path):
    bitmaps = parse_sheet(PIXEL_SHEET)
    contours = {name: bitmap_contours(rows) for name, rows in bitmaps.items()}
    advances = {name: CELL for name in contours}
    cmap = {}
    for letter in LETTERS:
        cmap[ord(letter)] = letter
        cmap[ord(letter.lower())] = letter  # lowercase reuses the capitals
    for digit, name in enumerate(DIGIT_NAMES):
        cmap[0x30 + digit] = name
    for name, cps in SYMBOL_CODEPOINTS.items():
        for cp in cps:
            cmap[cp] = name
    missing = sorted(set(cmap.values()) - set(contours))
    if missing:
        raise ValueError(f"Avium Pixel: no bitmap for {missing}")
    build_font(path, "Avium Pixel", "AviumPixel-Regular", contours, advances,
               cmap, x_height=CAP_HEIGHT, fixed_pitch=True)


def build_segment(path):
    contours, advances = {}, {}
    for name, (shape, adv) in segment_extras().items():
        contours[name], advances[name] = shape, adv
    for name, segs in SEGMENT_GLYPHS.items():
        contours[name] = [SEGMENT_SHAPES[s] for s in segs]
        advances[name] = CELL
    cmap = {}
    for digit, name in enumerate(DIGIT_NAMES):
        cmap[0x30 + digit] = name
    cmap[ord("O")] = "zero"  # a seven-segment O is the zero
    for name, chars in SEGMENT_LETTER_CODEPOINTS.items():
        for ch in chars:
            cmap[ord(ch)] = name
    for name in ("space", "hyphen", "plus", "period", "comma", "colon", "degree"):
        for cp in SYMBOL_CODEPOINTS[name]:
            cmap[cp] = name
    for name, shape in contours.items():
        if name == ".notdef":  # the only glyph with a hole
            continue
        for c in shape:
            if signed_area(c) >= 0:
                raise ValueError(f"Avium Segment: {name} has a counter-clockwise outer contour")
    build_font(path, "Avium Segment", "AviumSegment-Regular", contours, advances,
               cmap, x_height=SEG_M + SEG_H, fixed_pitch=False)


