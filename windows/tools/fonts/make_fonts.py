REQUIRED_TABLES = ("cmap", "glyf", "head", "hhea", "hmtx", "loca",
                   "maxp", "name", "OS/2", "post")


def verify(path):
    """Re-open a built font and check structure and outlines. Returns problems."""
    problems = []
    size = os.path.getsize(path)
    font = TTFont(path)
    for tag in REQUIRED_TABLES:
        if tag not in font:
            problems.append(f"missing table {tag}")
    order = font.getGlyphOrder()
    cmap = font.getBestCmap()
    formats = sorted({(t.platformID, t.platEncID, t.format) for t in font["cmap"].tables})
    if any(fmt != 4 for _, _, fmt in formats):
        problems.append(f"cmap subtables not all format 4: {formats}")
    glyph_set = font.getGlyphSet()
    glyf = font["glyf"]
    hmtx = font["hmtx"]
    n_contours = 0
    all_closed = True
    for name in order:
        rec = RecordingPen()
        glyph_set[name].draw(rec)
        contours, current = [], None
        for op, args in rec.value:
            if op == "moveTo":
                if current is not None:
                    problems.append(f"{name}: contour not closed before moveTo")
                    all_closed = False
                current = [args[0]]
            elif op == "lineTo":
                current.append(args[0])
            elif op == "closePath":
                contours.append(current)
                current = None
            elif op == "endPath":
                problems.append(f"{name}: open contour")
                all_closed = False
                current = None
            else:
                problems.append(f"{name}: unexpected segment {op}")
        if current is not None:
            problems.append(f"{name}: trailing open contour")
            all_closed = False
        areas = [signed_area(c) for c in contours]
        for c, a in zip(contours, areas):
            if len(c) < 3 or a == 0:
                problems.append(f"{name}: degenerate contour")
        if contours:
            if sum(areas) >= 0:
                problems.append(f"{name}: net winding is counter-clockwise")
            if areas[max(range(len(areas)), key=lambda i: abs(areas[i]))] >= 0:
                problems.append(f"{name}: largest contour is not clockwise")
        n_contours += len(contours)
        adv, lsb = hmtx[name]
        if glyf[name].numberOfContours > 0 and lsb != glyf[name].xMin:
            problems.append(f"{name}: lsb {lsb} != xMin {glyf[name].xMin}")
    widths = sorted({hmtx[n][0] for n in order})
    names = font["name"]
    family = names.getDebugName(1)
    print(f"{os.path.basename(path)}: family '{family}', {size} bytes, "
          f"{len(order)} glyphs, cmap {len(cmap)} code points {formats}, "
          f"{n_contours} contours, all closed: {'yes' if all_closed else 'NO'}, "
          f"advances {widths}")
    if size > MAX_BYTES:
        problems.append(f"file is {size} bytes (limit {MAX_BYTES})")
    return problems


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.normpath(os.path.join(here, "..", "..", "app", "ui", "fonts"))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=default_out, help="output folder")
    ap.add_argument("--no-verify", action="store_true", help="skip the re-open checks")
    args = ap.parse_args(argv)

    os.makedirs(args.out, exist_ok=True)
    pixel = os.path.join(args.out, "avium-pixel.ttf")
    segment = os.path.join(args.out, "avium-segment.ttf")
    build_pixel(pixel)
    build_segment(segment)
    if args.no_verify:
        return 0
    failed = False
    for path in (pixel, segment):
        for problem in verify(path):
            print(f"  PROBLEM: {problem}")
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
