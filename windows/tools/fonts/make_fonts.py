# Avium Segment: seven-segment geometry
#
#      aaa
#     f   b
#     f   b
#      ggg
#     e   c
#     e   c
#      ddd
# ---------------------------------------------------------------------------

SEG_X0, SEG_X1 = 90, 510  # digit body inside the 600-unit cell
SEG_T = 100  # bar thickness
SEG_GAP = 20  # tip pull-back; the visible diagonal gap is SEG_GAP * sqrt(2)
SEG_H = SEG_T // 2
SEG_L, SEG_R = SEG_X0 + SEG_H, SEG_X1 - SEG_H  # bar centre lines
SEG_B, SEG_TOP, SEG_M = SEG_H, CAP_HEIGHT - SEG_H, CAP_HEIGHT // 2
NARROW = 200  # advance of the decimal point, comma and colon
DOT = SEG_T  # square dot size


def hbar(x0, x1, y):
    """Horizontal hexagonal bar with tips at x0 and x1 (clockwise)."""
    h = SEG_H
    return [(x0, y), (x0 + h, y + h), (x1 - h, y + h),
            (x1, y), (x1 - h, y - h), (x0 + h, y - h)]


def vbar(x, y0, y1):
    """Vertical hexagonal bar with tips at y0 and y1 (clockwise)."""
    h = SEG_H
    return [(x, y0), (x - h, y0 + h), (x - h, y1 - h),
            (x, y1), (x + h, y1 - h), (x + h, y0 + h)]


def square(x0, y0, size):
    return [(x0, y0), (x0, y0 + size), (x0 + size, y0 + size), (x0 + size, y0)]


def _stroke_width(dx_plus_w, dy):
    """Horizontal width w of a slanted stroke whose perpendicular thickness is
    SEG_T, where the stroke's run is (dx_plus_w - w) over a rise of dy."""
    w = SEG_T
    for _ in range(30):
        w = SEG_T * math.hypot(dx_plus_w - w, dy) / dy
    return w


def rising_bar(x_left, y_bottom, x_right, y_top):
    """Slanted stroke going up and to the right, with horizontal ends.
    (x_left, y_bottom) is its bottom-left corner, (x_right, y_top) its top-right."""
    w = _stroke_width(x_right - x_left, y_top - y_bottom)
    pts = [(x_left, y_bottom), (x_right - w, y_top), (x_right, y_top), (x_left + w, y_bottom)]
    return [(round(x), round(y)) for x, y in pts]


def falling_bar(x_left, y_top, x_right, y_bottom):
    """Slanted stroke going down and to the right, with horizontal ends.
    (x_left, y_top) is its top-left corner, (x_right, y_bottom) its bottom-right."""
    w = _stroke_width(x_right - x_left, y_top - y_bottom)
    pts = [(x_right - w, y_bottom), (x_left, y_top), (x_left + w, y_top), (x_right, y_bottom)]
    return [(round(x), round(y)) for x, y in pts]


